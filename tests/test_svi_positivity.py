def test_grid_has_no_floored_cells():
    """End-to-end: a built grid must contain no near-zero implied vols.

    A floored cell shows up as sqrt(1e-8 / T), i.e. ~3e-4 — the exact symptom
    the batch QC gate was catching.
    """
    import pandas as pd

    from src.surface.grid_builder import interpolate_to_grid

    rows = []
    for T in (0.0833, 0.25, 0.5, 1.0, 2.0):
        for k in np.linspace(-0.40, 0.20, 25):
            iv = np.sqrt(max(_smile(np.array([k]))[0], 1e-8) / T)
            rows.append({"log_moneyness": k, "T": T, "implied_volatility": iv})

    _k, _t, grid = interpolate_to_grid(pd.DataFrame(rows), method="svi")
    assert np.isfinite(grid).all()
    assert grid.min() > 0.01
